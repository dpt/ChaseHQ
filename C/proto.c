static void draw_char(chqstate_t *state,
                      uint8_t     Achar,
                      uint8_t    *DE,    // screen address
                      uint8_t     Adash, // draw type
                      uint8_t     Cdash, // attribute
                      uint8_t    *DEdash,
                      uint8_t    *HLdash)
{
  uint8_t        Cglyphid; // was C
  uint8_t        Ctype;    // was C
  uint8_t        A;
  uint8_t        B;
  const uint8_t *HLfont;   // was HL
  uint8_t       *DEorig;   // was stacked

  Achar -= ' ';
  if (Achar == 0) {
    // Space
    DE++;
    HLdash++; // FIXME: Do we need to return these?
    return;
  }

  // Map ASCII to glyph IDs
  Cglyphid = 0x12;
  if (Achar >= ('A' - ' ')) goto dc_have_range;
  Cglyphid = 0x0B;
  if (Achar >= ('0' - ' ')) goto dc_have_range;
  Cglyphid = 0;
  Achar--;
  if (Achar == 0) goto dc_have_single;
  Cglyphid++;
  Achar -= 7;
  if (Achar == 0) goto dc_have_single;
  Cglyphid++;
  Achar--;
  if (Achar == 0) goto dc_have_single;
  Cglyphid++;
  Achar -= 3;
  if (Achar == 0) goto dc_have_single;
  Cglyphid++;
  goto dc_have_single;

dc_have_range:
  Cglyphid = Achar - Cglyphid;

dc_have_single:
  HLfont = &font[Cglyphid * 7]; // add symbol for glyph height

  Ctype = Adash;
  Ctype--;
  if (Ctype == 0) goto dc_generic; // 1
  Ctype--;
  if (Ctype == 0) goto dc_single_height; // 2
  Ctype--;
  if (Ctype == 0) goto dc_double_height; // 3
  Ctype--;
  if (Ctype == 0) goto dc_single_height_inverted; // 4
  Ctype--;
  if (Ctype == 0) goto dc_double_height_inverted; // 5

  // Otherwise it's type 0 or anything else
  DEorig = DE;
  B = 4; // iterations
  do {
    A = *HLfont;
    *DE = A;
    DE += 256;
    *DE = A;
    DE += 256;
    HLfont++;
  } while (--B > 0);
  DE -= 8 * 256;
  DE += 32;
  B = 3; // iterations
  do {
    A = *HLfont;
    *DE = A;
    DE += 256;
    *DE = A;
    DE += 256;
    HLfont++;
  } while (--B > 0);
  goto dc_set_double_attrs;

  // double height inverted
dc_double_height_inverted:
  DEorig = DE;
  B = 7;
  do {
    A = ~*HLfont;
    *DE = A;
    DE += 256;
    *DE = A;
    DE += 256;
    HLfont++;
  } while (--B > 0);
  goto dc_set_double_attrs;

dc_single_height_inverted:
  DEorig = DE;
  B = 7;
  do {
    A = ~*HLfont;
    *DE = A;
    HLfont++;
    DE += 256;
  } while (--B > 0);
  goto dc_set_single_attrs;

// Plots double-height glyphs. DE->screen HLfont->glyph def
dc_double_height:
  DEorig = DE;
  *DE = 0; // leave gap at top
  DE += 256;
  for (int i = 0; i < 7; i++) { // Conv: rolled
    A = *HLfont;
    *DE = A;
    DE += 256;
    *DE++ = *HLfont++; // was LDI, could reuse A
    DE--; // was DEC E, could remove if DE++ above is dropped
    DE += 256;
  }
  *DE = 0; // leave gap at bottom

dc_set_double_attrs:
  DE = DEorig + 1; // was POP DE, INC E
  *HLdash |= Cdash;
  HLdash += DEdash;
  *HLdash |= Cdash;
  HLdash -= DEdash; // was POP HLdash
  HLdash++; // was INC L
  return;

dc_single_height: // seems to store 9 rows
  DEorig = DE;
  *DE = 0; // leave gap at top
  DE += 256;
  for (int i = 0; i < 7; i++) { // Conv: rolled
    *DE++ = *HLfont++;
    DE--; // could drop
    DE += 256;
  }
  *DE = 0; // leave gap at bottom

dc_set_single_attrs:
  DE = DEorig + 1; // was POP DE
  *HLdash |= Cdash;
  HLdash++; // was INC L
  return;

dc_generic:
  DEorig = DE;
  B = 7; // iterations
  do {
    *DE = *HLfont;
    DE += 256;
    HLfont++;

    // A = D & 7;
    // JR NZ,$A0C7   ; If no rollover goto loop
    // D -= 8;
    // E += 32;
    // JR NC,$A0C7   ; If no rollover goto loop
    // D += 8;
  } while (--B > 0);
  DE = DEorig + 1; // was POP DE
  return;
}

