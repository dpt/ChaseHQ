// $8258
static void attract_mode(chqstate_t *state)
{
  int            carry = 0;
  uint8_t        SM_828c; // blinker - move to state?
  uint8_t        A;
  const uint8_t *HL;
  uint8_t        B;

  set_up_stage(state, stgmap(state, 0x5D2B)); // attract_data
  SM_828c = 0;
  state->speed = 400;
  for (;;) {
    A = keyscan(state);
    if (A == USERINPUT_FIRE)
      return;

    // TODO cpu_driver();

    HL = &attract_messages[0];
    B  = 1;
    A  = state->SM_8277;
    RRC(A);
    state->SM_8277 = A;
    if (!carry)
      B++;

    // Display 'B' messages
    do {
      A = *HL; // load flags
      HL = print_message(state, A, HL);
    } while (--B > 0);

    if (state->transition_control > 0)
      goto do_transition;

    // Alternate between credits and copyright messages.
    A = state->SM_828c;
    A ^= 1;
    state->SM_828c = A;
    HL = &credits_messages[0];
    if (A)
      HL = &copyright_messages[0];
do_setup:
    setup_overlay_messages(state, HL);
do_transition:
    transition(state);
    draw_screen(state);
  }
}

